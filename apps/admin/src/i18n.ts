/** Translate a French UI string to the current interface language (falls back to the original). */
export function tr(fr: string): string {
  if (lang === "fr") return fr;
  return EN[fr] ?? EN[fr.trim()] ?? fr;
}

/** Inline bilingual text (for strings that embed values). */
export const L = (fr: string, en: string) => (lang === "en" ? en : fr);
