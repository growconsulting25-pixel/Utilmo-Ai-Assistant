// Generates the DML seed migration from database/seed/<tenant>.json.
// Run once when creating a new tenant seed; never edit an applied migration.
import fs from "node:fs";
const [, , tenant = "utilmo", out] = process.argv;
const seed = JSON.parse(fs.readFileSync(`database/seed/${tenant}.json`, "utf8"));
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a) => `ARRAY[${a.map(q).join(",")}]::text[]`;
const o = seed.organization, a = seed.assistant;
let sql = `-- Seed tenant "${o.slug}" (generated by scripts/build-seed-migration.mjs from database/seed/${tenant}.json)\n`;
sql += `INSERT INTO organizations (slug, name, data_region) VALUES (${q(o.slug)}, ${q(o.name)}, ${q(o.data_region)}) ON CONFLICT (slug) DO NOTHING;\n`;
sql += `INSERT INTO assistants (organization_id, public_key, name) SELECT id, ${q(a.public_key)}, ${q(a.name)} FROM organizations WHERE slug = ${q(o.slug)} ON CONFLICT (public_key) DO NOTHING;\n`;
const asst = `(SELECT id FROM assistants WHERE public_key = ${q(a.public_key)})`;
const org = `(SELECT id FROM organizations WHERE slug = ${q(o.slug)})`;
sql += `INSERT INTO assistant_settings (assistant_id, organization_id, settings) VALUES (${asst}, ${org}, ${j(seed.settings)}) ON CONFLICT (assistant_id) DO NOTHING;\n`;
for (const d of seed.allowed_domains) sql += `INSERT INTO assistant_allowed_domains (organization_id, assistant_id, domain) VALUES (${org}, ${asst}, ${q(d)}) ON CONFLICT DO NOTHING;\n`;
for (const s of seed.services) {
  sql += `INSERT INTO recommended_services (organization_id, assistant_id, key, name, description, categories, problems, features, price_note, next_step, url, sort) VALUES (${org}, ${asst}, ${q(s.key)}, ${j(s.name)}, ${j(s.description)}, ${arr(s.categories)}, ${j(s.problems)}, ${j(s.features)}, ${j(s.price_note)}, ${q(s.next_step)}, ${q(s.url)}, ${s.sort}) ON CONFLICT (assistant_id, key) DO NOTHING;\n`;
}
for (const c of seed.conflicts) sql += `INSERT INTO knowledge_conflicts (organization_id, assistant_id, topic, description, source_urls, detected_by) VALUES (${org}, ${asst}, ${q(c.topic)}, ${q(c.description)}, ${arr(c.source_urls)}, 'seed');\n`;
fs.writeFileSync(out, sql);
console.log("wrote", out);
